-- 12. Find the average order value (AOV) for each sales channel
WITH order_value AS(
	SELECT o.sales_channel,o.order_id,ROUND(
		SUM(oi.quantity*oi.unit_price*(1-discount/100)),
		2) AS ord_value
	FROM orders o 
	JOIN order_items oi
	ON o.order_id=oi.order_id
	GROUP BY o.order_id
    ),
average_value AS(
	SELECT sales_channel,AVG(ord_value)AS avg_order_value
    FROM order_value
    GROUP BY sales_channel
    ) SELECT *FROM average_value
    ORDER BY avg_order_value DESC;
    
