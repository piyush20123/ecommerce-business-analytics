-- 20. Find the payment success rate for each payment mode.
WITH payment AS(
	SELECT payment_mode,
	COUNT(payment_id) AS total_payments,
	SUM(CASE WHEN payment_status='Successful' THEN 1 ELSE 0 END)AS successfull_payments
    FROM payments
    GROUP BY payment_mode
    )SELECT *,ROUND((successfull_payments/total_payments)*100,2) AS success_rate
    FROM payment
    ORDER BY success_rate DESC;
    
