-- 1. Find the top 10 customers based on total spending.
WITH spending AS(
	SELECT c.customer_id,c.name,
    ROUND(SUM(oi.quantity*oi.unit_price*(1-oi.discount/100)),2) AS total_spending
    FROM customers c
    JOIN orders o
    ON c.customer_id=o.customer_id 
    JOIN order_items oi
    ON o.order_id=oi.order_id
    GROUP BY c.customer_id,c.name
),customer_rank AS(
	SELECT *,
    RANK() OVER(
		ORDER BY total_spending DESC
        ) AS top_customers
        FROM spending
        )
	SELECT *FROM customer_rank
    WHERE top_customers <=10;
    
-- 2. Customers whose total spending is greater than the average spending of all customers.
WITH spending AS(
	SELECT c.customer_id,c.name,
    ROUND(SUM(oi.quantity*oi.unit_price*(1-oi.discount/100)),2) AS total_spending
    FROM customers c
    JOIN orders o
    ON c.customer_id=o.customer_id 
    JOIN order_items oi
    ON o.order_id=oi.order_id
    GROUP BY c.customer_id,c.name
    ), average_spending AS(
    SELECT *,
    ROUND(AVG(total_spending) OVER(),2) AS avg_spending
    FROM spending
    ) SELECT * FROM average_spending
    WHERE total_spending>avg_spending;
    
-- 3. Find customers who placed 3 or more orders.
SELECT 
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS total_orders
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.name
HAVING COUNT(o.order_id) >= 3;

-- 4. Find the total revenue generated by each customer segment.
